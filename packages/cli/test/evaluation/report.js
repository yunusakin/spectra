// Deterministic Markdown rendering of the evaluation results (no timings, paths or dates).
const pct = (value) => (value === null || value === undefined ? "n/a" : `${(value * 100).toFixed(1)}%`);
const num = (value) => (value === null || value === undefined ? "n/a" : String(value));
const list = (ids) => (ids.length ? ids.map((id) => `\`${id}\``).join(", ") : "–");
const row = (...cells) => `| ${cells.join(" | ")} |`;
const table = (header, rows) => [row(...header), row(...header.map(() => "---")), ...rows.map((cells) => row(...cells))].join("\n");

function renderReport(results, corpus) {
  const { summary, runs } = results;
  const caseOf = (id) => corpus.cases.find((entry) => entry.id === id);
  const normal = runs.filter((run) => run.level === "normal");
  const out = [];
  out.push("# Phase 1C — Retrieval Evaluation Report", "", "Generated by `test/evaluation.test.js` (`UPDATE_EVALUATION=1` regenerates it). Deterministic: no timings, paths or dates. Labels are hand-authored in `corpus.yaml`.", "");

  out.push("## Overall (normal budget, fallback case excluded)", "");
  out.push(table(["Metric", "Value"], [
    ["cases / runs (incl. budget levels)", `${summary.cases} / ${summary.runs}`],
    ["required recall", pct(summary.requiredRecall)],
    ["relevant recall", pct(summary.relevantRecall)],
    ["precision (acceptable objects neutral)", pct(summary.precision)],
    ["precision counting only labelled-irrelevant as wrong", pct(summary.precisionLabeledOnly)],
    ["false positives (labelled irrelevant / unlabeled)", `${summary.falsePositives} (${summary.falsePositivesLabeledIrrelevant} / ${summary.falsePositivesUnlabeled})`],
    ["false negatives (normal budget)", num(summary.falseNegativesNormal)],
    ["candidate tokens (objects)", num(summary.candidateTokens)],
    ["selected object tokens", num(summary.selectedObjectTokens)],
    ["pack tokens (actual)", num(summary.packTokens)],
    ["pack tokens (whole-file model)", num(summary.wholeFileBaselineTokens)],
    ["net pack change vs whole-file model", pct(summary.packTokenReduction)],
    ["status counts, normal budget", Object.entries(summary.statusCountsNormal).map(([k, v]) => `${k}=${v}`).join(", ")],
    ["status counts, all runs", Object.entries(summary.statusCounts).map(([k, v]) => `${k}=${v}`).join(", ")]
  ]), "");
  out.push("The whole-file model is the pre-addressability behaviour: policy + routing + whole matched rules/unresolved files. The net change is not a savings figure by itself: the current pack also retrieves feature objects and Repo Index records that the old routing never surfaced (see *Token efficiency*).", "");

  out.push("## Corpus and per-case outcome (normal budget)", "");
  out.push(table(["Case", "World", "Category", "Tier", "Selected", "Candidates", "FP", "FN", "Req. recall", "Rel. recall", "Precision", "Status"],
    normal.map((run) => {
      const entry = caseOf(run.case);
      return [`\`${run.case}\``, entry.world, entry.category, entry.tier, run.selected.length, run.candidates.length, run.falsePositives.length, run.falseNegatives.length, pct(run.metrics.requiredRecall), pct(run.metrics.relevantRecall), pct(run.metrics.precision), run.selection.status];
    })), "");

  out.push("## False positives and false negatives (normal budget)", "");
  for (const run of normal.filter((candidate) => candidate.falsePositives.length || candidate.falseNegatives.length)) {
    out.push(`### \`${run.case}\` — ${caseOf(run.case).task}`, "");
    for (const fp of run.falsePositives) {
      const reasons = run.reasons[fp.id].map((entry) => `${entry.reason}(${entry.via})`).join(", ");
      out.push(`- **false positive** \`${fp.id}\` (${fp.label}) via ${reasons}`);
    }
    for (const fn of run.falseNegatives) out.push(`- **false negative** \`${fn.id}\` (${fn.label}): ${fn.cause}`);
    out.push("");
  }

  out.push("## Per-reason analysis (normal budget)", "");
  out.push(table(["Reason", "Selected", "Relevant", "False positives", "Precision", "Avg tokens"],
    Object.entries(summary.reasons).map(([reason, data]) => [reason, data.selected, data.relevant, data.falsePositives, pct(data.relevant / data.selected), Math.round(data.tokens / data.selected)])), "");
  out.push("Retrieval misses attributable to *no signal at all*: " + (summary.missByCause["normal:retrieval-miss"] ?? 0) + " (normal budget). Budget and anchor exclusions are selection decisions, not retrieval misses.", "");

  out.push("## Relationship expansion (selected only through relationships/evidence)", "");
  out.push(table(["Kind", "Selected", "Relevant", "Tokens"], Object.entries(summary.relationshipOnly).map(([kind, data]) => [kind, data.selected, data.relevant, data.tokens])), "");

  out.push("## Lexical matching", "");
  for (const run of normal.filter((candidate) => caseOf(candidate.case).focus === "lexical")) {
    out.push(`- \`${run.case}\` — "${caseOf(run.case).task}"`);
    const hits = run.selected.map((id) => `${id} [${run.labels[id]}] ${run.reasons[id].filter((entry) => entry.reason === "feature-match" || entry.reason === "business-rule-match").map((entry) => `${entry.reason}(${entry.via})`).join(" ")}`.trim());
    out.push(`  - selected: ${hits.length ? hits.join("; ") : "nothing"}`);
    out.push(`  - missed: ${run.falseNegatives.length ? run.falseNegatives.map((miss) => `${miss.id} (${miss.cause})`).join(", ") : "–"}`);
  }
  out.push("");

  out.push("## Budget behaviour", "");
  const leveled = corpus.cases.filter((entry) => (entry.budgets ?? ["normal"]).length > 1);
  out.push(table(["Case", "Level", "Status", "Utilization", "Required recall", "Relevant recall", "Precision", "Included tokens", "Excluded (reason)"],
    leveled.flatMap((entry) => runs.filter((run) => run.case === entry.id).map((run) => [`\`${run.case}\``, run.level, run.selection.status, pct(run.selection.utilization), pct(run.metrics.requiredRecall), pct(run.metrics.relevantRecall), pct(run.metrics.precision), run.tokens.included, run.excluded.length ? run.excluded.map((item) => `${item.id} (${item.exclusion})`).join(", ") : "–"]))), "");

  out.push("## Token efficiency (exact object vs whole source)", "");
  out.push(table(["Source kind", "Selected tokens", "Whole-source tokens", "Reduction"], Object.entries(summary.byKind).map(([kind, data]) => [kind, data.selectedTokens, data.wholeTokens, pct(data.reduction)])), "");
  out.push(`Total: ${summary.exactObjectTokens} selected vs ${summary.wholeSourceTokens} whole-source tokens (${pct(summary.exactTokenReduction)} reduction). Sources are counted once per case; savings grow with source size (compare \`large-sources\`).`, "");
  out.push(table(["Case", "Source", "Objects", "Selected", "Whole source"], normal.filter((run) => ["large-sources", "rule-lexical", "spectra-approval-gating"].includes(run.case)).flatMap((run) => run.exactVsWhole.map((source) => [`\`${run.case}\``, source.source, source.objects, source.selectedTokens, source.wholeTokens]))), "");

  out.push("## Fallback (exact resolution unavailable)", "");
  for (const run of runs.filter((candidate) => candidate.fallback)) {
    out.push(`- \`${run.case}\`: map \`${run.selection.knowledge}\`, status ${run.selection.status}, whole-file tokens ${run.fallback.wholeFileTokens} vs exact-object equivalent ${num(run.fallback.exactTokens)} (\`${run.fallback.compareTo}\`), warnings: ${run.selection.warnings.join(", ") || "–"}`);
  }
  out.push("");

  out.push("## Knowledge coverage gaps (not retrieval failures)", "");
  for (const entry of corpus.cases.filter((candidate) => candidate.gaps?.length)) {
    out.push(`- \`${entry.id}\``);
    for (const gap of entry.gaps) out.push(`  - ${gap.type}: ${gap.note}`);
  }
  out.push("", "## Metric definitions", "");
  out.push("- **selected**: resolved objects in the final pack; **candidates**: selected + resolved objects excluded for budget/anchor (routing index files are ignored).");
  out.push("- **required / relevant recall**: labelled objects selected ÷ labelled objects; reported separately and `n/a` when a case has none.");
  out.push("- **precision**: selected required-or-relevant ÷ selected non-acceptable objects; a selected object with no label counts as a false positive.");
  out.push("- **false negative cause**: `retrieval-miss` (never a candidate), `budget-exclusion`/`anchor-exclusion` (found, then dropped by selection).");
  out.push("- **budget levels**: `normal` is the role budget; `tight` / `very-tight` leave 50% / 20% of the case's candidate tokens as room for optional context.", "");
  return `${out.join("\n")}\n`;
}

export { renderReport };
